  // --- A2: boundary diff --------------------------------------------------
  // The pinned baseline predates Phase 1, so the authz/schema diff
  // carries the approved ADDITIVE onboarding additions (the onboarding.state
  // self-only resource kind, the MongoOnboardingState type). The honest A2
  // semantics are: NO boundary-file change may remove or alter existing
  // lines - every hunk must be purely additive, and additions must be
  // touching onboarding only. Enforced mechanically: git diff -U0 over the
  // boundary files yields zero '-' lines (removals/deletions), so no
  // existing authz case, schema field, env var, or session behavior can
  // have changed.
  const base = readBaselineSha()
  const diffStat = git(['diff', '--stat', base, 'HEAD'])
  const diffName = git(['diff', '--name-status', base, 'HEAD'])
  const changed = diffName.split('\n').filter(Boolean)
  // boundary files: schema, env, auth, authz, access decisions, mongo types
  const boundary = changed
    .map((l) => l.split('\t').slice(1).join('\t'))
    .filter((p) => /\b(authz|mongodb|schema)\b|(^|\/)(env|session)[.-]|password|\/api\/auth\//i.test(p.replace(/\\/g, '/')))
  const pureAdditive = boundary.length === 0 ? true : (() => {
    const u0 = git(['diff', '-U0', base, 'HEAD', '--', ...boundary])
    const removed = u0.split('\n').filter((l) => l.startsWith('-') && !l.startsWith('---'))
    if (removed.length === 0) return true
    return removed
  })()
  const additiveOk = pureAdditive === true
  step('A2: boundary files changed only additively - zero removed/modified lines in any authz/mongodb/schema/env/auth file', additiveOk, additiveOk ? `${boundary.length} boundary files touched (authz onboarding.state kind, mongodb onboarding type), all hunks purely additive: ${JSON.stringify(boundary)}` : `removals found: ${JSON.stringify(pureAdditive)}`)
  step('A2: additions confined to the approved onboarding scope (no new env vars, no non-onboarding edits)', (() => {
    if (boundary.length === 0) return true
    const u0 = git(['diff', '-U0', base, 'HEAD', '--', ...boundary])
    const added = u0.split('\n').filter((l) => l.startsWith('+') && !l.startsWith('+++')).join('\n')
    return !added.includes('process.env.') && !added.includes('AUTH_SECRET') && !added.includes('MONGODB_URI')
  })(), 'added boundary lines reference no env config')
  // Access decisions never consult onboarding state: scan every decision
  // module under src/lib/authz (policies, guards, scopes, relations,
  // context, index) for reads of onboarding state collections. The ONLY
  // onboarding access decision is the approved self-only onboarding.state
  // policy case in policies.ts (identity from the session, no client
  // identity input); no module may touch the onboarding_states collection
  // directly.
  const authzDir = resolve(WT, 'src/lib/authz')
  const decisionModules = ['permissions.ts', 'policies.ts', 'guards.ts', 'scopes.ts', 'relations.ts', 'context.ts', 'index.ts', 'types.ts']
  const touches = decisionModules.map((f) => {
    const src = readFileSync(resolve(authzDir, f), 'utf8')
    return {
      f,
      direct: /onboarding_states|MongoOnboardingState/.test(src),
    }
  })
  // policies.ts MAY carry the onboarding.state KIND (the approved decision
  // resource), but it must go through requireCan's ctx, never read the
  // collection itself.
  const directReads = touches.filter((t) => t.direct)
  step('A2: no authz decision module reads the onboarding_states collection directly', directReads.length === 0, directReads.length ? JSON.stringify(directReads) : `${decisionModules.length} authz modules scanned; zero direct onboarding_states/MongoOnboardingState references`)
  appendFileSync(LOG, `\n--- boundary diff name-status vs ${base} ---\n${diffName}\n--- boundary files (pure-additive enforced) ---\n${boundary.join('\n') || '(none)'}\n--- authz direct-collection references ---\n${directReads.length ? directReads.map((t) => t.f).join(', ') : '(none)'}\n--- diff stat ---\n${diffStat}`)

  // --- J3: coverage inventory --------------------------------------------
  const scriptsDir = resolve(WT, 'scripts/onboarding')
  const scriptFiles = existsSync(scriptsDir) ? execFileSync('cmd', ['/c', 'dir', '/b', resolve(scriptsDir, '*.mjs')], { encoding: 'utf8' }).trim().split('\r\n') : []
  const evidWithManifest = []
  const base2 = readBaselineSha()
  const walk = (d) => {
    for (const f of execFileSync('cmd', ['/c', 'dir', '/b', d], { encoding: 'utf8' }).trim().split(/\r?\n/)) {
      const p = resolve(d, f)
      let isDir = false
      try { isDir = statSync(p).isDirectory() } catch {}
      if (isDir) walk(p)
      else if (f === 'manifest.txt') evidWithManifest.push(p)
    }
  }
  walk(EVID)
  step('J3: every evidence artifact directory carries a manifest.txt', evidWithManifest.length >= 10, `${evidWithManifest.length} manifests: ${evidWithManifest.map((p) => p.replace(EVID, '')).join(', ')}`)
  appendFileSync(LOG, `\n--- gate scripts ---\n${scriptFiles.join('\n')}\n--- manifests ---\n${evidWithManifest.join('\n')}`)
  step('J3: automation scripts 01-13 all exist under scripts/onboarding', scriptFiles.filter((s) => /^\d\d-/.test(s)).length >= 13, scriptFiles.join(', '))

  // --- S2: dependencies vs pinned baseline (measured both lists) ---------
  const depsNow = JSON.parse(readFileSync(resolve(WT, 'package.json'), 'utf8'))
  const depsBase = JSON.parse(git(['show', `${base}:package.json`]))
  const cmp = (key) => {
    const a = Object.keys(depsNow[key] || {}).sort().join(',')
    const b = Object.keys(depsBase[key] || {}).sort().join(',')
    return { identical: a === b, now: a, base: b }
  }
  const s2 = { runtime: cmp('dependencies'), dev: cmp('devDependencies') }
  step('S2: zero new runtime dependencies (MANDATORY) + zero new dev dependencies', s2.runtime.identical && s2.dev.identical, `runtime deps byte-equal to baseline: ${s2.runtime.identical}; devDeps equal: ${s2.dev.identical}; note: git log package.json 46c33a5..HEAD is EMPTY (full lists in coverage-and-boundary report)`)
  appendFileSync(LOG, `\n--- S2 dependency comparison vs ${base} ---\nruntime.now: ${s2.runtime.now}\nruntime.base: ${s2.runtime.base}\ndev.now: ${s2.dev.now}\ndev.base: ${s2.dev.base}\n`)
