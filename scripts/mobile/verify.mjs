  const faculty = await open({ width: 1280, role: 'faculty' })
  await faculty.page.screenshot({ path: resolve(out, 'faculty-desktop-1280.png') })
  check('Faculty desktop chrome remains role aware', await faculty.page.getByRole('button', { name: 'My Students', exact: true }).count() > 0)
