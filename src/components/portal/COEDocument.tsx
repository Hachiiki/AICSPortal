'use client'

import type { Student } from '@/lib/aics/types'
import { PALETTE } from '@/lib/aics/palette'

interface COEDocumentProps {
  student: Student
}

/**
 * The printable Certificate of Enrollment preview.
 * Rendered inside the COE modal and also what gets printed when the
 * user clicks Print / Save as PDF (controlled by the `.coe-print-area`
 * CSS rule in globals.css).
 *
 * LEGAL GUARDRAILS (see /legal/terms §5): this is an unofficial,
 * system-generated convenience — it must never be mistakable for a
 * school-issued certificate. It carries a visible UNOFFICIAL banner,
 * no registrar signature line, no seal, and a verification note.
 */
export function COEDocument({ student }: COEDocumentProps) {
  const today = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  })
  const totalUnits = student.subjects.reduce((sum, s) => sum + s.units, 0)

  return (
    <div className="font-sans" style={{ color: PALETTE.navy }}>
      {/* Letterhead */}
      <div
        className="flex items-center gap-4 pb-4"
        style={{ borderBottom: `2px solid ${PALETTE.navy}` }}
      >
        <img src="/aics-logo.svg" alt="" aria-hidden="true" className="w-16 h-16" />
        <div className="flex-1 text-center">
          <p className="text-[10px] uppercase tracking-widest" style={{ color: '#6b7280' }}>
            Republic of the Philippines
          </p>
          <p className="text-xl font-bold" style={{ color: PALETTE.navy }}>
            ASIAN INSTITUTE OF COMPUTER STUDIES
          </p>
          <p className="text-xs" style={{ color: '#6b7280' }}>
            {student.branchAddress}
          </p>
        </div>
      </div>

      {/* Unofficial-document banner — prints with the document. */}
      <div
        className="mt-4 px-4 py-2.5 text-center border-2 border-dashed"
        style={{ borderColor: PALETTE.ocean, background: `${PALETTE.mist}33` }}
      >
        <p className="text-[11px] font-bold uppercase tracking-[0.18em]" style={{ color: PALETTE.ocean }}>
          Unofficial · System-Generated Copy
        </p>
        <p className="text-[10px] mt-0.5" style={{ color: '#6b7280' }}>
          Generated by AICS Portal, an independent student project — not a school issuance, and
          carries no registrar signature or seal. For official certificates, request one from the
          Office of the Registrar.
        </p>
      </div>

      {/* Title */}
      <div className="text-center my-8">
        <p
          className="text-lg font-bold tracking-widest uppercase"
          style={{ color: PALETTE.navy }}
        >
          Certificate of Enrollment
        </p>
        <div className="w-32 h-0.5 mx-auto mt-2" style={{ background: PALETTE.ocean }} />
      </div>

      {/* Body */}
      <div className="text-sm leading-relaxed" style={{ color: PALETTE.navy }}>
        <p className="mb-4 pl-8">
          <strong>TO WHOM IT MAY CONCERN:</strong>
        </p>
        <p className="mb-4 pl-8 text-justify">
          This is to certify that, per the records of this portal, <strong>{student.fullName}</strong>,
          Student Number <strong>{student.studentNumber}</strong>, is enrolled at the{' '}
          {student.branch} branch for the {student.semester} of Academic Year{' '}
          {student.academicYear}, in the program <strong>{student.program}</strong>, currently in{' '}
          <strong>{student.yearLevel}</strong> level, Section <strong>{student.section}</strong>.
        </p>
        <p className="mb-4 pl-8 text-justify">
          The student is carrying a total load of <strong>{totalUnits} units</strong> consisting of{' '}
          {student.subjects.length} subjects for the said semester, as listed below:
        </p>
      </div>

      {/* Subjects table — scrolls horizontally on narrow screens; prints at full width */}
      <div className="mb-8 overflow-x-auto">
        <table className="w-full text-xs border-collapse min-w-[540px]" style={{ color: PALETTE.navy }}>
          <thead>
            <tr style={{ background: `${PALETTE.mist}55` }}>
              <th
                scope="col"
                className="border px-2 py-1.5 text-left font-semibold whitespace-nowrap"
                style={{ borderColor: PALETTE.navy }}
              >
                Code
              </th>
              <th
                scope="col"
                className="border px-2 py-1.5 text-left font-semibold"
                style={{ borderColor: PALETTE.navy }}
              >
                Subject Title
              </th>
              <th
                scope="col"
                className="border px-2 py-1.5 text-center font-semibold whitespace-nowrap"
                style={{ borderColor: PALETTE.navy }}
              >
                Units
              </th>
              <th
                scope="col"
                className="border px-2 py-1.5 text-left font-semibold whitespace-nowrap"
                style={{ borderColor: PALETTE.navy }}
              >
                Schedule
              </th>
              <th
                scope="col"
                className="border px-2 py-1.5 text-left font-semibold whitespace-nowrap"
                style={{ borderColor: PALETTE.navy }}
              >
                Room
              </th>
            </tr>
          </thead>
          <tbody>
            {student.subjects.map((s) => (
              <tr key={s.code}>
                <td className="border px-2 py-1.5" style={{ borderColor: `${PALETTE.mist}88` }}>
                  {s.code}
                </td>
                <td className="border px-2 py-1.5" style={{ borderColor: `${PALETTE.mist}88` }}>
                  {s.title}
                </td>
                <td
                  className="border px-2 py-1.5 text-center"
                  style={{ borderColor: `${PALETTE.mist}88` }}
                >
                  {s.units}
                </td>
                <td className="border px-2 py-1.5" style={{ borderColor: `${PALETTE.mist}88` }}>
                  {s.schedule}
                </td>
                <td className="border px-2 py-1.5" style={{ borderColor: `${PALETTE.mist}88` }}>
                  {s.room}
                </td>
              </tr>
            ))}
            <tr style={{ background: `${PALETTE.mist}33` }}>
              <td
                className="border px-2 py-1.5 font-bold"
                colSpan={2}
                style={{ borderColor: PALETTE.navy }}
              >
                Total
              </td>
              <td
                className="border px-2 py-1.5 text-center font-bold"
                style={{ borderColor: PALETTE.navy }}
              >
                {totalUnits}
              </td>
              <td
                className="border px-2 py-1.5"
                colSpan={2}
                style={{ borderColor: PALETTE.navy }}
              ></td>
            </tr>
          </tbody>
        </table>
      </div>

      <p className="mb-8 pl-8 text-sm text-justify" style={{ color: PALETTE.navy }}>
        This document was generated at the request of the above-named student and reflects the
        portal&rsquo;s records at the time of generation. It is not a certified school document and
        must not be presented as one; official certificates are issued only by the Office of the
        Registrar.
      </p>

      {/* Issuance footer — deliberately NO signature line and NO seal:
          a blank signable line over "Office of the Registrar" would
          invite forgery. Instead: an explicit no-signature notice. */}
      <div className="flex justify-end mt-12">
        <div
          className="text-center px-4 py-2.5 border rounded"
          style={{ borderColor: `${PALETTE.mist}AA`, background: `${PALETTE.mist}22` }}
        >
          <p className="text-xs" style={{ color: '#6b7280' }}>
            Generated on: {today}
          </p>
          <p className="text-[10px] font-semibold mt-1 uppercase tracking-wide" style={{ color: PALETTE.ocean }}>
            No signature · No seal · Non-official
          </p>
          <p className="text-[10px] mt-0.5" style={{ color: '#6b7280' }}>
            Verify enrollment with the Office of the Registrar.
          </p>
        </div>
      </div>
    </div>
  )
}
